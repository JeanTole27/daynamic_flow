  String operator [](String key) => _m[key] ?? key;

  /// Reemplaza `{nombre}` por los valores de [args].
  String fmt(String key, Map<String, Object> args) {
    var out = this[key];
    args.forEach((k, v) => out = out.replaceAll('{$k}', '$v'));
    return out;
  }

  /// Mensaje para un código de error del servidor o de la app.
  String error(String code, {String? detail}) {
    final key = 'err_$code';
    if (!_m.containsKey(key)) return this['err_generic'];
    return fmt(key, {'m': detail ?? '?'});
  }
